const DICTS: Record<ResolvedLanguage, Dict> = { zh, en };

/** 把 {{name}} 占位替换成实际值 */
function interpolate(template: string, params?: Record<string, unknown>): string {
	if (!params) return template;
	return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
		const value = params[key];
		return value === undefined || value === null ? match : String(value);
	});
}

/**
 * 取指定语言的文案。找不到 key 时按 zh → key 顺序回退，
 * 这样漏翻一条也不会显示成空白。
 */
export function translate(
	lang: ResolvedLanguage,
	key: string,
	params?: Record<string, unknown>,
): string {
	const dict = DICTS[lang] ?? zh;
	const template = dict[key] ?? zh[key];
	if (template === undefined) return key;
	return interpolate(template, params);
}

export function makeTranslator(lang: ResolvedLanguage) {
	return (key: string, params?: Record<string, unknown>) => translate(lang, key, params);
}

export type Translator = ReturnType<typeof makeTranslator>;

/** 所有 key（用于测试两种语言是否对齐） */
export function allKeys(): Array<{ key: string; zh: boolean; en: boolean }> {
	const keys = new Set([...Object.keys(zh), ...Object.keys(en)]);
	return [...keys].sort().map((key) => ({ key, zh: key in zh, en: key in en }));
}
